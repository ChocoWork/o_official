const parsed = new Map<number, ReadonlySet<string>>();

function holidaysOf(year: number): ReadonlySet<string> | undefined {
	const cached = parsed.get(year);
	if (cached) return cached;
	const row = HOLIDAYS_BY_YEAR[year];
	if (row === undefined) return undefined;
	const set = new Set(row.split(' '));
	parsed.set(year, set);
	return set;
}

/** 祝日・休日なら true、表のある年で祝日でなければ false、表の無い年は undefined。 */
export function isJpHoliday(date: string): boolean | undefined {
	const matched = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
	if (!matched) throw new RangeError(`invalid date: ${date}`);
	return holidaysOf(Number(matched[1]))?.has(`${matched[2]}${matched[3]}`);
}
